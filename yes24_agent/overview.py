def _cached_rows(
    query: str, section: str, settings: Settings, arm: str = ARM_YES24
) -> tuple[dict, dict, bool] | None:
    """G2 히트면 _run_search와 **같은 3튜플**(병합 결과, 요청 로컬 state, 보강 기시도)을
    복원해 돌려준다 — 호출자는 캐시 유무를 몰라도 되는 같은 계약을 받는다.

    담는 것이 파싱 행(G1)이 아니라 **병합 완료 결과 + 출처 레지스트리**인 이유: 파싱은
    각도당 50~100ms뿐이고 응답 미스의 바닥에 남는 ~1.1s는 보강 플래너 LLM 콜과 2차 각도
    병합이다(실측 3.84s → 1.07s 첫 delta). 레지스트리를 함께 담아야 행의 cite_as가 가리키는
    source_id가 살아나고(등록은 URL 멱등이라 이후 상세 열람도 같은 id로 갱신된다),
    checked_at은 그 관측 시각 그대로 남는다 — 카드 표기가 정직해지는 것이 행 TTL을
    신선도 정책으로 다룰 수 있는 근거다.
    **행마다 사본을 준다**(deepcopy): 소비자는 행에 상세 발췌를 얹고 레지스트리를 갱신하므로,
    사본이 아니면 다음 히트가 앞 요청의 관측을 물려받는다.
    """
    entry = _rows.get(_rows_key(query, section, settings, arm), settings.overview_rows_ttl_s)
    if entry is None:
        return None
    result, sources, boost_tried = deepcopy(entry)
    state = _new_search_state(settings)
    state[SOURCES_STATE_KEY] = sources
    logger.info(f"overview 행 캐시 히트(G2) qlen={len(query)} rows={result.get('result_count')}")
    return result, state, boost_tried


def _store_rows(
    query: str,
    section: str,
    settings: Settings,
    result: dict,
    state: dict,
    boost_tried: bool,
    arm: str = ARM_YES24,
) -> None:
    """생성이 실제로 쓴 행 집합을 G2에 담는다 — **성공·비어 있지 않은 결과만**.

    실패·0건은 담지 않는다: 그 판정은 degraded 음성 캐시(_negatives)의 몫이고, 여기에
    담으면 같은 실패를 두 저장소가 서로 다른 TTL로 각각 서빙한다(판정 중복 구현 금지).
    """
    if not _has_hits(result):
        return
    # **잘린 증거는 담지 않는다** — search_timeout을 음성 캐시에 박지 않는 것과 같은 근거다
    # (예산이 검색을 끊었으므로 다음 요청이 같은 결과를 낼 이유가 없다). 종전엔 이 규율이
    # degraded 경로에만 있어서, 예산으로 보강이 취소된 **성공 결과**(status=ok·행>0)가
    # 행 TTL(600s) 동안 그대로 서빙됐다: '초등 과학책 추천'은 정상 46행인데 보강이 잘린
    # 런은 1행이고(2026-08-31 예산 축소 주입 실측), 그 1행이 10분간 모든 후속 요청의
    # 근거가 된다 — 한 번의 느린 순간이 캐시 창 전체를 오염시키는 자리다.
    if state.get(SEARCH_TRUNCATED_STATE_KEY):
        logger.info(
            f"overview 행 캐시 저장 생략(잘린 증거) "
            f"qlen={len(query)} rows={result['result_count']}"
        )
        return
    _rows.set(
        _rows_key(query, section, settings, arm),
        deepcopy((result, state.get(SOURCES_STATE_KEY, []), boost_tried)),
        settings.overview_rows_ttl_s,
        settings.overview_cache_max_entries,
    )


def _has_hits(result: dict | None) -> bool:
    """"행이 있는 성공 결과"의 단일 판정 — 병합·보강 채택·회수 확보가 같은 술어를 본다
    (종전엔 같은 판정이 세 벌로 흩어져 있었다: _merge_search_results 안의 _has_rows,
    0건 보강 채택 조건, 재시도 블록의 status·result_count 검사)."""
    return bool(
        result is not None
        and result.get("status") == "ok"
        and result.get("result_count", 0) > 0
    )


async def _safe_search(
    queries: list[str], section: str, state: dict, label: str, order: str = ""
) -> dict | None:
    """보강 검색 도구 호출 1회 — 예상 밖 예외는 None으로 삼킨다(보강은 포기지 실패 사유가
    아니다). 도구는 예상 오류를 status="error"로 삼키지만 예상 밖 예외는 gather 밖으로
    올라온다(yes24_search 주석) — 여기서 안 삼키면 0건 보강은 "1차 결과 폴백" 계약이,
    무인용 보강은 F2(reset은 재검색 성공 확정 뒤에야 나간다)가 깨진다. CancelledError는
    BaseException이라 그대로 전파된다. order는 1차 RECENT 각도(W1)가 쓴다.
    """
    try:
        return await yes24_search(queries, section, SimpleNamespace(state=state), order=order)
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"overview 보강 재검색({label}) 실패 — 포기: {exc!r}")
        return None


# 이 요청에서 **검색이 예산으로 잘렸다**는 사실(요청 로컬 state). 하류의 degraded 판정이
# "온전한 증거 위에서 내려졌는가"를 이 값으로 답하고, 음성 캐시가 그 답으로 저장 여부를
# 가른다(_store_payload). 예산으로 검색을 자르는 지점이 하나뿐이라(_bounded_search·
# _retry_search 진입 가드) 신호원도 하나다 — 파생 추정(행 수가 적다 등)으로 대신하면
# "보강이 잘렸다"와 "보강할 게 없었다"를 뭉갠다(2026-08-31 첫 시도의 실패).
SEARCH_TRUNCATED_STATE_KEY = "overview_search_truncated"


async def _bounded_search(
    queries: list[str], section: str, state: dict, label: str, *, deadline: float, order: str = ""
) -> list[dict]:
    """각도를 **하나씩 독립 Task로** 띄우고 몫(deadline)까지 **도착한 것만** 거둔다.

    `_harvest_details`의 이식이다 — 상세 열람이 2026-08-27에 같은 형상의 결함으로 같은
    답을 냈다("한 배치가 아니라 행별 Task인 이유는 지각 1건이 도착분을 인질로 잡지 못하게
    하기 위해서다", `_spawn_detail_fetches`). 종전엔 여러 각도를 `yes24_search` 한 콜의
    gather로 묶어 통째로 wait_for했고, 몫을 넘기면 **이미 조회·파싱까지 끝난 각도의 행까지
    함께 버려졌다**: 반환 None이 `_merge_search_results`의 `_has_hits` 필터에서 통째로
    탈락하므로 결과가 "부분 회수"가 아니라 **"시간만 쓰고 0행"**이었다. 저신호 질의에서
    보강은 1차 1~6행을 26~57행으로 바꾸는 유일한 장치라(2026-08-31 실측) 이 all-or-nothing이
    곧 답의 유무였다 — 예산 축소 실런에서 46행→1행·50행→2행이 났고 그중 하나는 1행 때문에
    관련성 게이트가 접혀 무노출로 끝났다.

    보강 각도(RECENT)·보강 재검색이 공유하는 단일 상한 지점이라는 역할은 그대로다. 각도당
    한 콜로 쪼개도 Yes24 요청 수는 같고(같은 검색어 집합), 동시성·요청률도 공유
    `Yes24Client`의 Semaphore·rps가 종전과 같이 유계한다. 같은 state를 여러 콜이 공유해도
    안전한 근거는 1차 2각도 병렬과 같다 — 등록 루프가 await 없는 순차 구간이라 source_id가
    유일·단조다(`yes24_search` "레이스 0"). 취소된 콜이 이미 등록한 출처가 남는 것도
    종전과 같이 무해하다(공개·검증 집합은 프롬프트 동봉 행의 id로 필터된다 —
    `_attempt` prompt_ids).

    반환은 **도착한 각도들의 결과 목록**이고 호출자가 그대로 병합에 splat한다 — 각도별
    순위 리스트가 RRF의 입력 단위라(`_merge_search_results`) 쪼개진 반환이 오히려 병합의
    자연 단위다. 하나도 못 거두면 빈 목록이고, 그 자리의 종전 None과 하류 의미가 같다.

    끊은 사실은 state에 남긴다(SEARCH_TRUNCATED_STATE_KEY) — 지각분을 잘랐다는 것은 증거가
    온전하지 않다는 뜻이고, 하류가 그것을 알아야 불안정한 판정을 캐시에 박지 않는다.

    **이 전환은 병합의 입력 단위도 바꾼다 — 무해한 리팩터가 아니다**(2026-08-31 독립 리뷰).
    `_merge_search_results`는 `queries[0]`(첫 관측 각도)로만 버킷을 가르는데, 종전 멀티쿼리
    단일 콜은 같은 상품을 한 번만 담고 2번째 이후 각도를 `queries`에 이름만 덧붙였다 —
    그래서 **여러 각도 공통 등장이 RRF에서 통째로 버려졌다**(3각도에 나온 상품도 기여 1개).
    각도당 독립 콜은 각 콜이 자기 순위 전체를 담고 source_id가 URL 멱등이라 **공통 등장이
    이제야 합산된다**. 관측: 3각도×20행에서 프롬프트 동봉 상위 10 중 **4행 교체·순서 전면
    변경**. 방향은 병합 독스트링이 원래 내세우던 쪽이지만(그 문장은 단일 콜에서는 한 번도
    참이 아니었다), 보강 경로의 프롬프트 행이 실제로 바뀌는 변경이다.

    **순위 품질 판정(2026-08-31, 라이브 각도 원본 21콜·9질의 재생 — 존치).** 지적된 위험은
    산술로는 크다: Σ1/(60+rank)에서 **3각도 등장은 rank 122까지, 2각도는 61까지** 1각도 1위를
    이기고, 각도 깊이가 24인 실물에서는 각도 수가 rank를 **항상** 이긴다. 그리고
    `minority_kind_weight=0.8`은 이 위험에 **닿지 않는다** — 20위×3각도를 1각도 1위 아래로
    내리려면 0.437 미만이 필요하다(10위면 0.383·40위면 0.546). "일부만 상쇄"가 아니라 한 칸도
    못 뒤집는다는 뜻이라 위 문장을 이 판정으로 대체한다.
    그런데 **전제가 실물에서 성립하지 않는다**: 다각도 6질의 전수에서 **3각도 이상 공통 상품이
    0건**이고(최대 2각도 — 채식주의자 19·토익 14·해리포터 7), 각도들이 서로 꽤 disjoint하다.
    그리고 겹침이 이렇게 얕다는 것은 **효과의 주범이 합산이 아니라는 뜻**이다 — 단일 콜은
    각도를 순서대로 이어 붙이므로 늦게 도는 각도의 모든 행이 앞 각도의 행 수만큼 rank 페널티를
    먹는다: 「해리포터 전집」에서 각도 '해리포터 세트'의 1위가 **rank 40**에서, '해리포터'의
    1위가 rank 16에서 출발했다(가장 정확한 각도가 가장 크게 눌렸다). 그래서 겹침이 0인
    「초등 과학책 추천」도 순위가 바뀐다('어린이 과학 도서' 1위가 rank 26 → 1). 관련성이 아니라
    **호출 순서**가 순위를 정하던 자리이므로, 이 전환은 트레이드오프가 아니라 결함 제거다.
    실측 결과 상위 14의 오프토픽 비율은 **단일 콜 형상 38.5% → 각도별 리스트 36.1%**로 오히려
    낮고, 교체가 일어난 두 케이스는 육안으로도 개선이다 — 「해리포터 전집」은 종전 형상이
    **비공식 가이드북**을 1·4·7·10·13위로 올리고 실제 세트를 밀어냈는데 현행은 해리 포터
    1~2권·5~7부·1~4부·Complete Collection을 1~7위에 올린다(병합 독스트링이 원래 내세우던
    "전집 SKU 상승"이 이제야 실제로 성립한다). 「토익 교재 추천」은 종전 1·5위가 IoT 지식능력
    검정 교재였는데 현행 상위 14에는 0건이다.
    **본문 눈가림 심사(60페어·4질의×seed 15, 대칭 필드, 독립 심사관 — 존치 유지, 단 근거가
    다르다)**: 종합 **종전 31 · 현행 26 · 무 3으로 실질 동률**이고, 위 "육안으로도 개선"은
    **기계 순위에서만 참이다**. 질의별로는 두 전승이 **정반대를 가리킨다** —
    「해리포터 전집」 현행 15-0(국내 번역본 전집 경로 1~4부·5~7부를 주는가, eBook 합본·미국판
    원서만 주는가), 「토익 교재 추천」 **종전** 15-0. 토익에서 IoT 잡음이 빠진 것은 맞지만 그
    자리에 들어온 것이 **ETS Vol.5/Vol.4의 묶음 변형 9종**이라 선택지가 오히려 붕괴했다
    (심사 사유: "9개 id가 사실상 두 시리즈의 묶음 변형"). 「채식주의자 줄거리」 종전 12-3은
    커버리지가 아니라 **서두 정직성**에서 갈렸고(줄거리 부재 명시 13/15 대 5/15), 심사관은 현행
    행이 영문판 5종 같은 **근접 중복**이라 본문이 카탈로그 모드로 빨려든다고 적었다.
    → **패인의 정체는 근접 중복 행이다.** 각도별 rank 재기준은 각 각도의 최상위를 올리는데 그
    최상위가 대개 **같은 베스트셀러의 판형 변형들**이라, 변형이 곧 정답인 질의(해리포터 세트)는
    이기고 변형이 잡음인 질의(토익 시리즈 조합)는 진다. 라이브 확인: 「채식주의자 줄거리」 카드
    12장 중 미국판 ×2·영국판 ×2가 연달아 그려진다. 이 전환을 되돌릴 일이 아니라 **동일 상품
    변형의 중복 노출을 다루면** 현행의 패인이 사라진다(별도 백로그).
    회수량 이득(1행→34행·무노출→노출)과 순위 지표(오프토픽 38.5%→36.1%)는 그대로이고 본문이
    동률이므로 존치는 유지되지만, **"본문도 좋아졌다"고는 말할 수 없다.**
    **기각한 대안**: `search_rrf_k`를 60 → 8로 낮추면(rank가 각도 수를 다시 이기는 임계는
    k<8.5) 오프토픽이 33.6%로 더 낮지만, 개선분이 **단일 각도 질의**(나니아 14→13·김애란 8→5)
    에서 나온다 — k가 각도 수 대 rank 균형이 아니라 소수 kind 강등의 상대 효과를 바꾼 것이라
    의도한 레버가 아니다. 지금 근거로는 표준값 60을 건드리지 않는다.
    """
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        state[SEARCH_TRUNCATED_STATE_KEY] = True
        return []
    if not queries:
        # `asyncio.wait`는 **빈 집합에서 ValueError**다(종전 `_safe_search([])`는
        # error_type="empty_query"로 깔끔히 마감했다). 현 호출부 둘은 비어 있지 않음을
        # 보장하지만 세 번째가 생기는 순간 500이 된다 — 예산 사건이 아니므로 무표시로 뺀다.
        return []
    tasks = [
        asyncio.create_task(_safe_search([query], section, state, label, order=order))
        for query in queries
    ]
    try:
        _, pending = await asyncio.wait(tasks, timeout=remaining)
    except BaseException:
        # 고아 Task 금지: `asyncio.wait`는 취소돼도 기다리던 Task를 취소하지 않는다
        # (종전 `wait_for`는 자기 future를 취소했다 — 그 성질이 여기서 사라진다).
        # 이 함수가 취소되는 실경로가 있다: `_run_search`는 기본 각도가 실패하면
        # `recent_task.cancel()`로 이 코루틴을 취소한다. 걷어주지 않으면 진행 중이던
        # Yes24 조회가 주인 없이 계속 돌아 요청 예의와 로그를 모두 더럽힌다.
        for task in tasks:
            task.cancel()
        raise
    for task in pending:
        task.cancel()  # 취소는 도구의 조회까지 내려간다(_harvest_details와 같다)
    if pending:
        state[SEARCH_TRUNCATED_STATE_KEY] = True
        logger.info(
            f"overview 보강 검색({label}) 지각 {len(pending)}/{len(tasks)}각도 취소 — "
            f"도착 {len(tasks) - len(pending)}각도로 진행"
        )
    arrived: list[dict] = []
    for task in tasks:
        if task in pending or task.cancelled():
            continue
        # _safe_search가 예상 오류를 이미 삼켰다(None) — 예상 밖 예외만 여기 남는다.
        if task.exception() is not None:
            continue
        result = task.result()
        if result is not None:
            arrived.append(result)
    return arrived


def _minority_kind_weights(rows: dict[int, dict], weight: float) -> dict[int, float] | None:
    """행 집합에서 **소수 kind 행**에 곱할 RRF 가중치 — 강등할 게 없으면 None.

    Yes24 검색은 domain=ALL 키워드 색인이라 질의 의도와 무관한 상품이 제목 토큰 하나로
    딸려 온다(2026-08-28 실측: '겨울에 읽을 소설 추천' → 원문 0건 → 플래너 3각도 병합
    53행에 수면양말·트리장식·무릎담요·책갈피가 섞여 동봉 14행 중 4행). 그 유입을 거르는
    신호는 **질의와 무관한 구조 신호**다: 이 집합에서 다수를 이루는 kind(사이트가 붙인
    상품 종류 라벨)가 곧 이 질의가 실제로 매칭한 상품 종류이고, 소수 kind 행은 같은
    검색어에 우연히 걸린 다른 종류다. 그래서 kind 값을 코드가 알 필요가 없다 — 목록·
    분류·키워드 없이 **집합 내 상대 다수**만 본다(비도서가 정답인 질의는 그 kind가 다수라
    자동 보존: '아이패드 케이스' 48행 전부 문구/GIFT → 강등 대상 0).

    판정 규칙(전부 상대 판정 — 임계 하드코딩 없음):
    - **다수 = 절반 초과**. 최다 kind가 나머지 전부보다 많을 때만 "이 질의가 매칭한
      종류"라고 말할 수 있다. 어느 kind도 과반이 아닌 혼재 집합에선 kind가 신호를 갖지
      않으므로 강등하지 않는다 — 실측 반례가 근거다('나니아 연대기 전집' 46행 = 직수입
      양서 23·외서 7·DVD 4·Blu-ray 4·LP 2·도서 2·eBook 2·CD 1·직수입일서 1: 최다가 정확히
      절반이라 게이트가 닫히고, 열렸더라도 정답 SKU인 도서 '나니아 연대기'는 기본
      가중치에서 동봉 안에 남는다 — config 주석의 경계 스윕).
    - **kind 미관측 행은 강등 대상도 집계 대상도 아니다**(파서의 키 생략 계약과 같은
      규율 — 관측되지 않은 것으로 판정하지 않는다).
    - 가중치는 곱셈이라 강등폭이 RRF 점수 격차에 유계다 — **제거가 아니라 강등**이고,
      다수 kind 행이 상한을 못 채우면 소수 행은 그대로 동봉된다(실측: 단일 각도 '겨울
      소설' 24행은 도서 15행뿐이라 강등 후에도 문구/GIFT 1행이 동봉 14행에 남는다).

    weight >= 1.0(롤백 레버)이거나 강등 대상이 하나도 없으면 None을 돌려준다 — 호출자는
    종전 경로(정렬·조기 반환)를 바이트 동일하게 유지한다.
    """
    if weight >= 1.0:
        return None
    counts = Counter(kind for row in rows.values() if (kind := row.get("kind")))
    if not counts:
        return None
    dominant, dominant_count = counts.most_common(1)[0]
    if dominant_count * 2 <= sum(counts.values()):
        return None
    return {
        sid: weight
        for sid, row in rows.items()
        if (kind := row.get("kind")) and kind != dominant
    } or None


# 프롬프트 동봉 행에서 빼는 내부 메타 — _build_prompt_rows와 _identity_key가 **같은 목록**을
# 쓴다(판정 하나, 정의 하나). 여기 있는 키는 "본문·카드가 볼 수 없는 것"이라는 한 가지
# 뜻이고, 그래서 이 목록의 여집합이 곧 "사용자가 두 행을 구분할 수 있는 근거 전부"다.
_PROMPT_EXCLUDED_KEYS = frozenset(
    {"source_id", "url", "checked_at", "queries", "type", "author_no", "goods_no", "image_url"}
)
# 동일성 키는 위 여집합에서 둘을 더 뺀다. cite_as는 행을 가리키는 참조 표면이지 상품
# 사실이 아니라 행마다 다를 수밖에 없다. sale_index는 상품의 사실이 아니라 **그 등록이
# 쌓은 판매 실적**이라, 같은 책이 두 번 등록되면 판매가 두 쪽으로 갈려 반드시 어긋난다
# (실측 147102749=96 대 147102747=12 — 나머지 필드는 전부 같았다). 실적이 갈렸다는 것은
# 같은 상품이라는 증거이지 다른 상품이라는 증거가 아니다. rating·review_count도 같은
# 부류지만 **빼지 않는다** — 저장 프롬프트 행 91런에서 이 둘로 갈린 쌍은 0건이라(제외해도
# 잉여 7칸으로 동일) 관측되지 않은 실패 모드에 미리 분기하지 않는다.
# 반대로 type은 되돌린다: 웹 문서와 상품은 제목이 같아도 서로의 근거가 될 수 없다(원칙 4a).
_IDENTITY_EXCLUDED_KEYS = (_PROMPT_EXCLUDED_KEYS | {"cite_as", "sale_index"}) - {"type"}


def _identity_key(row: dict) -> str:
    """행이 **사용자에게 보여줄 사실 전부**를 담은 키. 두 행의 키가 같다는 것은 프롬프트에도
    카드에도 똑같은 글자가 실린다는 뜻이고, 그러면 고를 축이 하나도 없다.

    제목(또는 제목+kind) 기준이 아닌 이유는 실측이다(저장 프롬프트 행 91런·1,248칸,
    2026-08-31): 제목만 같은 잉여 42칸 중 21칸은 매체 축(도서/eBook/오디오북)이고, kind까지
    같은 21칸 중에도 14칸은 번역·판형이 실제로 다른 별개 상품이었다('데미안' 열림원 김연신
    역 대 민음사 전영애 역, 'Economy in Society' 판매가 85,920원 대 204,120원). 제목 기준
    병합은 그 14칸을 **다른 책을 지우는** 수정이 된다. 이 키가 잡는 것은 7칸(0.56%)뿐이고,
    같은 코퍼스에서 오합치는 0건이다.

    **알려진 한계**: sale_index를 키에서 빼므로 남는 행의 판매지수가 버려지는 행보다 낮을 수
    있고, 그 값은 프롬프트 행과 순위 문자열(`_ranked_value`)의 재료다. 세 코퍼스(프롬프트 행
    91런·campaign 14런·풀 295행)에서 역전은 0건이나 **두 값이 다 관측된 고유 케이스가 1건
    (96 대 12)뿐이라 표본이 근거를 지탱하지 못한다**. 순서가 판매지수를 따르는 것은 기본 검색
    정렬(인기순)과의 상관일 뿐 보장이 아니다 — 오버뷰는 RECENT 각도를 함께 돌리고, 실제 그
    쌍은 RECENT 각도에서 rank 1·2로 왔다(그 각도만 보면 순서가 지켜진 게 우연이다). 수정
    전에는 두 값이 다 실렸으므로 이 방향으로 나빠지지는 않는다."""
    return json.dumps(
        {key: value for key, value in row.items() if key not in _IDENTITY_EXCLUDED_KEYS},
        ensure_ascii=False,
        sort_keys=True,
        default=repr,
    )


def _merge_search_results(
    *sources: dict | None, k: int, minority_kind_weight: float
) -> dict | None:
    """n개 도구 반환을 **RRF(Reciprocal Rank Fusion)**로 병합한다 — 상품별 점수는 그 상품이
    등장한 각도들의 Σ 1/(k+rank)(rank는 1부터, k=config.search_rrf_k — RAG-Fusion 표준값,
    근거는 config 주석)이고 점수 내림차순이 병합 순서다. **여러 각도에 공통 등장한 상품이
    자연 상승**하고(합산 — 웨이브2 실측: 전집 SKU가 기본각도 rank20·세트각도 rank6인데
    라운드로빈 인터리브가 재절단해 3/3런 프롬프트 탈락), 한 각도에만 있는 잡음·구판은
    하락한다. 동점은 인자 순서 → 원 rank(종전 인터리브의 선순위 의미 유지 — 앞 소스가
    이긴다).

    각도의 단위는 "소스 × 관측 변형"이다: 각 소스의 행을 queries[0](그 행을 처음 관측한
    변형 — 도구 병합의 귀속 필드)로 버킷해 버킷 하나를 순위 리스트 하나로 취급한다 —
    병합본의 재병합(저신호 경로)도 같은 규칙으로 각도가 복원된다.
    **종전에 여기 있던 "멀티쿼리 단일 콜의 변형별 블록 이어붙기도 같은 규칙으로 복원된다"는
    문장은 삭제했다(2026-08-31)** — 오버뷰에는 멀티쿼리 단일 콜이 더는 없고(전 호출부가
    각도당 1콜), 그 문장은 사실도 아니었다: 단일 콜은 같은 상품을 한 번만 담고 2번째 이후
    각도를 queries에 이름만 덧붙이므로 **공통 등장이 buckets[queries[0]]에서 통째로 버려졌다**
    (위 "공통 등장이 자연 상승"은 각도당 독립 콜로 바뀐 뒤에야 실제로 성립한다 —
    `_bounded_search` 독스트링). 1차 2각도(기본·RECENT 정렬)·보강(제안 또는 축약)·저신호 병합이 전부
    이 한 함수를 쓴다(수정 1지점). 하류 절단(_attempt)은 이 순서를 그대로 신뢰한다 —
    변형 간 균형은 RRF 점수가 소유하므로 별도 라운드로빈 재절단은 없다(웨이브3 삭제).

    소수 kind 강등(minority_kind_weight, 2026-08-28): 점수 정렬 직전에 소수 kind 행의
    점수에 가중치를 곱한다 — 판정·근거는 _minority_kind_weights, 값은
    config.overview_minority_kind_weight(1.0이면 아래 정렬·조기 반환이 종전과 바이트
    동일). 이 함수가 오버뷰의 **모든 병합 경로**(1차 2각도·0건 보강·저신호 보강·재생성)를
    지나므로 강등 지점도 여기 하나다. 저신호 보강처럼 병합본이 primary로 다시 들어오는
    경로에선 이미 강등된 순서가 버킷 rank로 한 번 더 반영되지만, 두 효과가 같은 방향이라
    순서가 뒤집히지 않는다(재병합 자체의 성질은 _retry_search docstring 참조).

    구별 불가능한 행 제거(2026-08-31): 정렬 순서를 소비하면서 _identity_key가 같은 행은
    뒤엣것을 버린다. Yes24는 같은 상품을 goods_no만 다르게 두 번 등록해 두는 일이 있고
    (실측 '비공식 해리포터 가이드북 시리즈 전5권 세트' 147102747/147102749), URL이 다르니
    register_source가 서로 다른 source_id를 줘 두 행이 나란히 프롬프트에 실린다. 본문은 그
    상품을 한 번 말하면서 마커를 둘 다 붙였고(저장 답변 코퍼스: 인접 마커와 함께 언급된
    119회 중 94회) 프론트는 출처당 카드 하나를 그리므로 같은 카드가 두 장 떴다. 기준이
    제목이 아니라 **사실 전부**인 근거는 _identity_key. 버릴 것이 없으면 아래 조기 반환은
    종전과 바이트 동일하다(단일 각도 부가 필드 보존 경로).

    유효 소스(status=ok·행>0)가 하나뿐이고 단일 각도면(강등 대상도 없고 버릴 행도 없으면)
    그 dict를 그대로 돌려주고(searches 등 부가 필드 보존), 하나도 없으면 첫 non-None을 그대로
    돌려준다(0건·error dict 그대로 — 판정은 호출자 몫). 같은 상품은 같은 state에 등록돼
    source_id가 동일하므로 (register_source URL 멱등) id 기준 합산·dedup이 곧 상품
    합집합이다.
    """

    valid = [source for source in sources if _has_hits(source)]
    if not valid:
        return next((source for source in sources if source is not None), None)
    ranked: list[list[dict]] = []
    for source in valid:
        buckets: dict[str, list[dict]] = {}
        for row in source["results"]:
            buckets.setdefault((row.get("queries") or [""])[0], []).append(row)
        ranked.extend(buckets.values())
    scores: dict[int, float] = {}
    tiebreak: dict[int, tuple[int, int]] = {}
    first_row: dict[int, dict] = {}
    for angle, results in enumerate(ranked):
        for rank, row in enumerate(results, start=1):
            sid = row["source_id"]
            scores[sid] = scores.get(sid, 0.0) + 1.0 / (k + rank)
            if sid not in first_row:
                first_row[sid] = row
                tiebreak[sid] = (angle, rank)
    demoted = _minority_kind_weights(first_row, minority_kind_weight)
    keys = {sid: _identity_key(row) for sid, row in first_row.items()}
    if len(ranked) == 1 and demoted is None and len(set(keys.values())) == len(keys):
        return valid[0]
    weights = demoted or {}
    seen: set[str] = set()
    rows: list[dict] = []
    for sid in sorted(
        scores, key=lambda sid: (-scores[sid] * weights.get(sid, 1.0), tiebreak[sid])
    ):
        # 구별 불가능한 행은 병합 순서에서 **뒤엣것만** 버린다 — 앞엣것이 이미 그 상품의
        # 모든 사실을 싣고 있으므로 정보 손실이 구조적으로 불가능하고, 빈 칸은 절단선
        # (_attempt) 바깥의 다음 후보가 채운다.
        if keys[sid] in seen:
            continue
        seen.add(keys[sid])
        rows.append(first_row[sid])
    if len(valid) == 1:
        # 단일 소스의 멀티 변형 재정렬 — 부가 필드(searches 등)는 보존한다.
        return {**valid[0], "result_count": len(rows), "results": rows}
    return {"status": "ok", "result_count": len(rows), "results": rows}


