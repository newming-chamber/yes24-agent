def _relaxed_queries(query: str) -> list[str]:
    """토큰 축약 사다리 — 공백 토큰을 뒤에서 하나씩 뗀 변형들을 만든다. **플래너 제안이
    없을 때만 쓰는 폴백**이다(_retry_search — 완화의 1순위는 모델이 쓴 제안이고, 이 blind
    변환은 리콜 바닥을 지키는 최후 수단이다: 깊은 단일수록 남은 앞부분이 다른 상품의 제목
    리터럴이 돼 무관 상품을 공급한다는 2026-08-27 회수 진단 실측).

    검색엔진의 일반적인 "검색어 완화" 구조다(형태소·동의어 지식 없음 — 구조 변환만,
    원칙 4). 예: "a b c" → ["a b", "a"]. 단일 토큰이면 뗄 것이 없어 빈 목록이다.
    상한은 도구의 `yes24_search_max_queries`(plan_queries cap)가 그대로 적용된다.
    """
    tokens = query.split()
    return [" ".join(tokens[:i]) for i in range(len(tokens) - 1, 0, -1)]


