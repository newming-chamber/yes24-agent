def normalize_query(query: str) -> str:
    """캐시 키용 질의 정규화(G2) — **구조 변환만** 한다(동의어·키워드 목록 금지, 원칙 4).

    NFKC(전각·호환 문자) → 트림·내부 공백 축약 → casefold(대소문자). 같은 질의의 표기
    변형이 같은 키로 수렴해 히트율이 코드 순증 없이 오른다.
    """
    return " ".join(unicodedata.normalize("NFKC", query).split()).casefold()


