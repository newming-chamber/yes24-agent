_MARKER_RE = re.compile(r"\[\d+\]")


def _replay_chunks(text: str, replay_ms: int) -> list[str]:
    """캐시 replay 본문을 페이싱 조각으로 나눈다 — 조각 합계는 항상 원문과 같다.

    2026-08-26 사용자: 캐시 히트의 전문 1회 delta("즉시 인쇄물")가 생성형 UX 문법을
    깬다 — 내용은 캐시 그대로 두고 **방출만** 짧게 페이싱한다. 조각 수는
    replay_ms // 틱에서 유도하되 본문 길이를 넘지 않으므로, 본문이 아무리 길어도 총
    재생 시간은 (조각 수 − 1) × 틱 ≤ replay_ms — 상한이 지연을 지배한다. replay_ms
    0 이하는 종전 전문 1조각(롤백 레버). 인용 마커 [n]은 칩 렌더가 조각 단위로
    일어나므로 경계에서 쪼개지 않는다(경계가 마커 안이면 마커 끝으로 민다).
    """
    limit = int(replay_ms // (_REPLAY_TICK_S * 1000))
    if limit < 2 or len(text) < 2:
        return [text]
    size = -(-len(text) // min(len(text), limit))  # ceil — 조각 수 ≤ limit 보장
    marker_spans = [m.span() for m in _MARKER_RE.finditer(text)]
    chunks: list[str] = []
    start = 0
    while start < len(text):
        end = min(start + size, len(text))
        for span_start, span_end in marker_spans:
            if span_start < end < span_end:
                end = span_end
                break
        chunks.append(text[start:end])
        start = end
    return chunks


