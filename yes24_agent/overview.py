class _Verdict(NamedTuple):
    """관련성 게이트 판정 3축 + 관측 재검색어.

    - relevant: 노출 가치(F-B). false면 전량 폐기 → degraded="irrelevant".
    - needs_detail: 상세 접지 필요(G-4). true면 상세 열람 + 이어쓰기 1회.
    - target_missing: **지목된 대상 미도달**(2026-08-28 A). true면 방류 밸브를 열지 않고
      회수 재검색+재생성 1회로 간다 — "본문이 근거로 삼을 대상이 회수되지 않았다"의 한
      갈래이고 다른 갈래가 기존 무인용(유효 마커 0)이라, 둘은 **같은 재시도 배관**을 쓴다.
    - queries: target_missing일 때만 실리는 관측 기반 재검색어(2026-08-28 B). 투기
      플래너 제안보다 앞선다(_retry_search 우선순위: 관측 → 제안 → 축약).
    """

    relevant: bool
    needs_detail: bool
    target_missing: bool = False
    queries: tuple[str, ...] = ()


