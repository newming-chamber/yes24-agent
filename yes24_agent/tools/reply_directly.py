"""잡담·창작 탈출구 도구.

첫 턴 도구 강제(ANY, config force_first_turn_tool) 시절의 탈출구다: 검색이 전혀 불필요한
순수 대화·창작 요청까지 억지로 검색하지 않도록, 이 도구를 호출하면 다음 턴이 AUTO로 풀려
도구 없이 답할 수 있었다. 2026-07-29 AUTO 상시 전환(기본값) 후에는 구조적 필수가 아니지만,
모델이 "검색이냐 직답이냐"를 명시적으로 선언하는 관측 신호로 여전히 자발 호출한다(실측) —
로그에 남는 직답 사유가 QA 진단값이라 유지한다. ANY로 되돌리면 다시 탈출구 역할을 한다.

이 도구는 출처를 내지 않으므로 여기로 빠진 턴은 runner의 무접지 판정(유효 인용 0건 ∧
(마커 ∨ 출처))에도 걸리지 않는다 — 즉 **도구 설명이 이 경로의 유일한 계약**이다. 그래서 설명은
"무엇을 질문받았나"가 아니라 "답변에 무엇을 쓸 것인가"를 기준으로 쓴다(2026-07-20: 추천 요청을
조언으로 분류해 이 도구로 빠진 뒤 무출처로 책을 지목하는 rule 4a 위반 실측).
"""

import logging

logger = logging.getLogger(__name__)


async def reply_directly(reason: str) -> dict:
    """답변에 실재하는 대상·확인 가능한 사실을 전혀 담지 않을 때만 사용하는 직답 선언 도구.

    판단 기준은 질문의 형식이 아니라 **당신이 쓰려는 답변의 내용**이다. 답변이 사용자가 준 입력과
    시간이 지나도 변하지 않는 일반 지식만으로 이루어질 때 호출한다(인사·잡담·감정 나눔·글쓰기·
    번역·요약·문장 다듬기·계산·개념 설명).

    반대로 답변에 특정 책·상품·인물·사건처럼 실재하는 대상의 이름이나 그 속성(제목·저자·가격·
    평점·재고·순위·규정·시점)이 하나라도 들어갈 예정이면 이 도구를 쓰지 말고 `yes24_search`·
    `yes24_fetch`·`web_search` 등으로 확인한다. 추천·조언·의견 요청도 같다 — 답으로 실재하는
    책·상품을 지목한다면 그것은 대화가 아니라 검증 가능한 주장이므로, 아무리 잘 아는 대상이라도
    이번 턴의 도구 결과로 확인해 `[n]`으로 인용해야 한다. 이전 턴에서 이미 언급된 대상도
    예외가 아니다 — 앞선 대화에 나왔다는 것은 근거가 아니므로, 그중 하나를 고르거나 다시
    설명하는 답변도 이번 턴에 새로 확인해야 한다.

    Args:
        reason: 답변에 확인 가능한 사실이 들어가지 않는다고 판단한 짧은 이유.

    Returns:
        status="ok"만 담은 dict. 이 호출 뒤 도구 없이 사용자에게 바로 답한다.
    """
    logger.info("reply_directly reason=%r", reason)
    return {"status": "ok"}
