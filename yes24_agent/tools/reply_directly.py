"""잡담·창작 탈출구 도구.

첫 모델 턴에 도구 호출을 강제(FunctionCallingConfigMode.ANY)해 모델이 자체 지식으로 직답하지
못하게 하는데, 검색이 전혀 불필요한 순수 대화·창작 요청까지 억지로 검색하면 어색하다. 그런
요청일 때 모델이 이 도구를 호출하면, 도구 실행 응답이 생겨 다음 턴이 AUTO로 풀리고 모델이
도구 없이 바로 답한다. 즉 "검색이냐 직답이냐"를 모델의 암묵 판단이 아니라 명시적 도구 선택으로
만들어, Yes24 상품·정책·웹 사실을 자체 지식으로 지어내는 것을 구조로 막는다(출처 최대화).
"""


async def reply_directly(reason: str) -> dict:
    """Yes24 상품·정책이나 외부 웹 사실이 전혀 필요 없는 순수 대화·창작 요청에만 사용한다.

    인사·잡담·감정 나눔·글쓰기·번역·요약·문장 다듬기·계산·아이디어·의견·조언처럼 검색 없이
    답할 수 있을 때 호출한다. 반대로 특정 책·상품의 제목·저자·가격·평점·재고·순위, Yes24 정책·
    이용 규정, 오늘의 뉴스·시세 같은 **확인 가능한 사실**을 물으면 아무리 잘 아는 것 같아도
    이 도구를 쓰지 말고 `yes24_search`·`yes24_fetch`·`web_search` 등 검색 도구를 사용한다.

    Args:
        reason: 검색이 필요 없는 순수 대화·창작 작업이라고 판단한 짧은 이유.

    Returns:
        status="ok"만 담은 dict. 이 호출 뒤 도구 없이 사용자에게 바로 답한다.
    """
    return {"status": "ok"}
